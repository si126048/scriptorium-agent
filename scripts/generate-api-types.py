"""Generate TypeScript request contracts directly from the unified FastAPI OpenAPI schema."""
import argparse
import json
from pathlib import Path
from scriptorium.research.api import create_app


def ts(node):
    if '$ref' in node:
        return 'Schemas[' + json.dumps(node['$ref'].split('/')[-1]) + ']'
    for key in ('anyOf', 'oneOf'):
        if key in node:
            return '(' + ' | '.join(ts(n) for n in node[key]) + ')'
    if 'enum' in node:
        return ' | '.join(json.dumps(x, ensure_ascii=False) for x in node['enum'])
    kind = node.get('type')
    if kind == 'array':
        return 'Array<' + ts(node.get('items', {})) + '>'
    if kind == 'object' or 'properties' in node:
        props = node.get('properties', {})
        required = node.get('required', [])
        if not props:
            return 'Record<string, ' + (ts(node['additionalProperties']) if isinstance(node.get('additionalProperties'), dict) else 'unknown') + '>'
        return '{ ' + '; '.join(json.dumps(k) + ('' if k in required else '?') + ': ' + ts(v) for k, v in props.items()) + ' }'
    return {'string': 'string', 'integer': 'number', 'number': 'number', 'boolean': 'boolean', 'null': 'null'}.get(kind, 'unknown')


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    schema = create_app().openapi()
    result = '// Generated by python scripts/generate-api-types.py; do not edit.\nexport interface Schemas {\n'
    result += '\n'.join('  ' + json.dumps(name) + ': ' + ts(node) + ';' for name, node in sorted(schema['components']['schemas'].items()))
    result += '\n}\nexport interface Endpoints {\n'
    for path, operations in sorted(schema['paths'].items()):
        if not path.startswith('/api/v2/'):
            continue
        for method, operation in operations.items():
            if method not in {'get', 'put', 'post', 'delete', 'patch'}:
                continue
            request = operation.get('requestBody', {}).get('content', {}).get('application/json', {}).get('schema', {})
            response = next((value for code, value in operation.get('responses', {}).items() if code.startswith('2')), {})
            response = response.get('content', {}).get('application/json', {}).get('schema', {})
            result += '  ' + json.dumps(method.upper() + ' ' + path) + ': { request: ' + ts(request) + '; response: ' + ts(response) + ' };\n'
    result += '}\n'

    target = Path('web/src/features/workspace/api/generated.ts')
    if args.check:
        if target.read_text(encoding='utf-8') != result:
            raise SystemExit('OpenAPI TypeScript contracts are stale')
    else:
        target.write_text(result, encoding='utf-8')


if __name__ == '__main__':
    main()
